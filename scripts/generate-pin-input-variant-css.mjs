import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
const path = new URL("../src/components/pin-input/pin-input-variants.css", import.meta.url);
const variants = {
  outline: ["transparent", "transparent", "border-strong"],
  surface: ["var(--brick-color-surface-raised)", "var(--brick-color-surface-raised)", "border-strong"],
  soft: ["var(--brick-color-surface-subtle)", "var(--brick-color-surface-subtle)", "border-subtle"],
  subtle: ["var(--brick-color-surface-subtle)", "var(--brick-color-surface-subtle)", null],
  ghost: ["transparent", "var(--brick-color-surface-subtle)", null],
  plain: ["transparent", "transparent", null],
  underline: ["transparent", "transparent", "border-strong"],
};
let output = "/* Generated by scripts/generate-pin-input-variant-css.mjs. */\n@layer brick.components {\n";
for (const [key, width] of [["initial", null], ["sm", "30rem"], ["md", "48rem"], ["lg", "64rem"], ["xl", "80rem"]]) {
  if (width) output += `@media (min-width: ${width}) {\n`;
  for (const [variant, [bg, hover, border]] of Object.entries(variants)) {
    const underline = variant === "underline";
    output += `.brick-pin-input[${key === "initial" ? "data-variant" : `data-variant-${key}`}="${variant}"] {
  --brick-pin-input-background: ${bg};
  --brick-pin-input-hover-background: ${hover};
  --brick-pin-input-border: ${border ? `var(--brick-color-${border})` : "transparent"};
  --brick-pin-input-hover-border: ${border ? "var(--brick-pin-input-tone-border)" : "transparent"};
  --brick-pin-input-border-width: ${underline ? "0 0 var(--brick-border-width)" : "var(--brick-border-width)"};
  --brick-pin-input-resolved-radius: ${underline ? "0px" : "var(--brick-pin-input-radius)"};
  --brick-pin-input-seam: ${underline ? "0px" : "calc(-1 * var(--brick-border-width))"};
  --brick-pin-input-focus-shadow: ${underline ? "0 var(--brick-border-focus-width) 0 0" : "0 0 0 var(--brick-border-focus-width)"};
}\n`;
  }
  if (width) output += "}\n";
}
output += "}\n";
if (process.argv.includes("--check")) assert.equal(await readFile(path, "utf8"), output);
else await writeFile(path, output);
