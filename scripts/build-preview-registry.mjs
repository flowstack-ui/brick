import { readFile, writeFile } from "node:fs/promises";
import ts from "typescript";
import { createHash } from "node:crypto";

const root = new URL("../", import.meta.url);
const app = await readFile(new URL("playground/src/app/PlaygroundApp.tsx", root), "utf8");
const ast = ts.createSourceFile("PlaygroundApp.tsx", app, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
const bindings = new Map();
for (const statement of ast.statements) {
  if (!ts.isImportDeclaration(statement)) continue;
  const names = statement.importClause?.namedBindings;
  if (names && ts.isNamedImports(names)) for (const item of names.elements) {
    bindings.set(item.name.text, { path: statement.moduleSpecifier.text, symbol: item.propertyName?.text ?? item.name.text });
  }
}
let table;
function visit(node) {
  if (ts.isVariableDeclaration(node) && node.name.getText(ast) === "playgroundModules") table = node.initializer;
  ts.forEachChild(node, visit);
}
visit(ast);
while (table && (ts.isSatisfiesExpression(table) || ts.isAsExpression(table))) table = table.expression;
if (!table || !ts.isObjectLiteralExpression(table)) throw new Error("Missing canonical playground module table");
const rows = table.properties.map(property => {
  if (!ts.isPropertyAssignment(property) || !ts.isObjectLiteralExpression(property.initializer)) throw new Error("Unsupported module registration");
  const id = property.name.text;
  const parts = Object.fromEntries(property.initializer.properties.map(part => [part.name.text, bindings.get(part.initializer.text)]));
  if (!parts.Page || !parts.scenarios || parts.Page.path !== parts.scenarios.path) throw new Error(`Unpaired source for ${id}`);
  return { id, path: parts.Page.path, page: parts.Page.symbol, scenarios: parts.scenarios.symbol };
}).sort((a, b) => a.id.localeCompare(b.id));

const lines = rows.map(row => `  ${JSON.stringify(row.id)}: {\n    load: () => import(${JSON.stringify(row.path)}).then(m => ({ Page: m.${row.page}, scenarios: m.${row.scenarios} })),\n    source: () => import(${JSON.stringify(row.path.replace(/\.js$/, ".tsx?raw"))}).then(m => m.default),\n    height: ${row.id === "aspect-ratio" ? 640 : 720},\n  },`).join("\n");
const output = `// Generated by scripts/build-preview-registry.mjs from the canonical app module table.\nimport type { ComponentType } from "react";\nimport type { ScenarioDefinition } from "../shared/Scenario.js";\ninterface PreviewRegistration { load: () => Promise<{ Page: ComponentType; scenarios: readonly ScenarioDefinition[] }>; source: () => Promise<string>; height: number }\nexport const previewRegistry = {\n${lines}\n} satisfies Record<string, PreviewRegistration>;\nexport type PreviewComponent = keyof typeof previewRegistry;\nexport function isPreviewComponent(value: string): value is PreviewComponent { return Object.prototype.hasOwnProperty.call(previewRegistry, value); }\n`;
const destination = new URL("playground/src/preview/preview-registry.ts", root);
const inventory = [];
for (const row of rows) {
  const path = new URL(row.path.replace(/\.js$/, ".tsx"), new URL("playground/src/app/", root));
  const source = await readFile(path, "utf8");
  if (/document\.documentElement\s*(?:\.[\w]+\s*=|\.setAttribute|\.style)|document\.body\.style|localStorage\.|sessionStorage\.|history\.(?:replaceState|pushState)/.test(source)) {
    throw new Error(`${row.id}: component pages must not mutate shell-global settings or document styles`);
  }
  inventory.push({ component: row.id, source: path.pathname.slice(root.pathname.length), sourceSha256: createHash("sha256").update(source).digest("hex"), mode: "inline", sourceMode: "paired-page-source", heightPolicy: "authored-layout", scopePolicy: "authored-local-providers-and-props-win", reviewSignals: { explicitAppearance: /Appearance|data-brick-appearance/.test(source), explicitDirection: /\bdir=/.test(source), locale: /LocaleProvider/.test(source), portalOrShadowRoot: /createPortal|attachShadow/.test(source) } });
}
const inventoryOutput = JSON.stringify({ schema: "flowstack.playground-preview-inventory.v1", components: inventory }, null, 2) + "\n";
const inventoryPath = new URL("playground/preview-inventory.json", root);
if (process.argv.includes("--check")) {
  if (await readFile(destination, "utf8") !== output) throw new Error("Preview registry is stale. Run node scripts/build-preview-registry.mjs");
  if (await readFile(inventoryPath, "utf8") !== inventoryOutput) throw new Error("Preview inventory is stale. Run node scripts/build-preview-registry.mjs");
} else {
  await writeFile(destination, output);
  await writeFile(inventoryPath, inventoryOutput);
}
console.log(`Verified ${rows.length} paired preview modules.`);
