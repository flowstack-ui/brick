import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const outputPath = resolve(import.meta.dirname, "../src/components/textarea/textarea-variants.css");
const check = process.argv.includes("--check");
const breakpoints = [
  ["initial", null],
  ["sm", "30rem"],
  ["md", "48rem"],
  ["lg", "64rem"],
  ["xl", "80rem"],
];
const variants = {
  outline: ["transparent", "transparent", "var(--brick-color-border-strong)", "var(--brick-color-accent-border)"],
  surface: ["var(--brick-color-surface-raised)", "var(--brick-color-surface-raised)", "var(--brick-color-border-strong)", "var(--brick-color-accent-border)"],
  soft: ["var(--brick-color-surface-subtle)", "var(--brick-color-surface-subtle)", "var(--brick-color-border-subtle)", "var(--brick-color-accent-border)"],
  subtle: ["var(--brick-color-surface-subtle)", "var(--brick-color-surface-subtle)", "transparent", "transparent"],
  ghost: ["transparent", "var(--brick-color-surface-subtle)", "transparent", "transparent"],
  plain: ["transparent", "transparent", "transparent", "transparent"],
  underline: ["transparent", "transparent", "var(--brick-color-border-strong)", "var(--brick-color-accent-border)"],
};

function rules(key) {
  const attribute = key === "initial" ? "data-variant" : `data-variant-${key}`;
  return Object.entries(variants).map(([variant, [background, hoverBackground, border, hoverBorder]]) => {
    const selector = `.brick-textarea.brick-control-size[${attribute}="${variant}"]`;
    const underline = variant === "underline";
    return `${selector} {
  --brick-textarea-background: ${background};
  --brick-textarea-hover-background: ${hoverBackground};
  --brick-textarea-border: ${border};
  --brick-textarea-hover-border: ${hoverBorder};
  border-width: ${underline ? "0 0 var(--brick-border-width)" : "var(--brick-border-width)"};
  border-radius: ${underline ? "0" : "var(--brick-textarea-radius)"};
  padding-inline: ${underline ? "0" : "var(--brick-textarea-padding-inline)"};
}
${selector}:focus-within {
  box-shadow: ${underline
    ? "0 var(--brick-border-focus-width) 0 0 var(--brick-textarea-focus-ring)"
    : "0 0 0 var(--brick-border-focus-width) var(--brick-textarea-focus-ring)"};
}`;
  }).join("\n");
}

const body = breakpoints.map(([key, width]) => {
  const content = rules(key).split("\n").map((line) => width ? `  ${line}` : line).join("\n");
  return width ? `@media (min-width: ${width}) {\n${content}\n}` : content;
}).join("\n");
const output = `/* Generated by scripts/generate-textarea-variant-css.mjs. */\n@layer brick.components {\n${body.split("\n").map((line) => `  ${line}`).join("\n")}\n}\n`;

if (check) {
  assert.equal(await readFile(outputPath, "utf8"), output, "textarea variant CSS is stale");
} else {
  await writeFile(outputPath, output);
}
