import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
const path = new URL("../src/components/tags-input/tags-input-variants.css", import.meta.url);
const variants = {
  outline: ["transparent", "transparent", "border-strong", "accent-border"],
  surface: ["var(--brick-color-surface-raised)", "var(--brick-color-surface-raised)", "border-strong", "accent-border"],
  soft: ["var(--brick-color-surface-subtle)", "var(--brick-color-surface-subtle)", "border-subtle", "accent-border"],
  subtle: ["var(--brick-color-surface-subtle)", "var(--brick-color-surface-subtle)", null, null],
  ghost: ["transparent", "var(--brick-color-surface-subtle)", null, null],
  plain: ["transparent", "transparent", null, null],
  underline: ["transparent", "transparent", "border-strong", "accent-border"],
};
let output = "/* Generated by scripts/generate-tags-input-variant-css.mjs. */\n@layer brick.components {\n";
for (const [key, width] of [["initial", null], ["sm", "30rem"], ["md", "48rem"], ["lg", "64rem"], ["xl", "80rem"]]) {
  if (width) output += `@media (min-width: ${width}) {\n`;
  for (const [variant, [bg, hover, border, hoverBorder]] of Object.entries(variants)) {
    const underline = variant === "underline";
    output += `.brick-tags-input[${key === "initial" ? "data-variant" : `data-variant-${key}`}="${variant}"] {
  --brick-tags-input-background: ${bg};
  --brick-tags-input-hover-background: ${hover};
  --brick-tags-input-border: ${border ? `var(--brick-color-${border})` : "transparent"};
  --brick-tags-input-hover-border: ${hoverBorder ? `var(--brick-color-${hoverBorder})` : "transparent"};
  --brick-tags-input-border-width: ${underline ? "0 0 var(--brick-border-width)" : "var(--brick-border-width)"};
  --brick-tags-input-resolved-radius: ${underline ? "0" : "var(--brick-tags-input-radius)"};
  --brick-tags-input-inset: ${underline ? "0px" : "max(0px, calc(var(--brick-control-size-padding-inline) - var(--brick-space-2)))"};
  --brick-tags-input-draft-inset: ${underline ? "0px" : "var(--brick-space-2)"};
  --brick-tags-input-focus-shadow: ${underline ? "0 var(--brick-border-focus-width) 0 0" : "0 0 0 var(--brick-border-focus-width)"};
  --brick-tags-input-neutral-item-background: var(--brick-color-${["soft", "subtle"].includes(variant) ? "surface-base" : "surface-subtle"});
}\n`;
  }
  if (width) output += "}\n";
}
output += "}\n";
if (process.argv.includes("--check")) assert.equal(await readFile(path, "utf8"), output);
else await writeFile(path, output);
