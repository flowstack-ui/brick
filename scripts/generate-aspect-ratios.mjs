import { readFile, writeFile } from "node:fs/promises";

const source = JSON.parse(await readFile(new URL("../src/styles/tokens.tokens.json", import.meta.url), "utf8"));
const values = Object.fromEntries(Object.entries(source.reference.aspectRatio)
  .filter(([key]) => !key.startsWith("$"))
  .map(([key, token]) => {
    if (typeof token.$value !== "number" || !Number.isFinite(token.$value) || token.$value <= 0) throw new Error(`Invalid aspect ratio: ${key}`);
    for (const appearance of ["light", "dark"]) {
      if (source.semantic[appearance]["aspect-ratio"][key].$value !== `{reference.aspectRatio.${key}}`) throw new Error(`Ratio ${key} must be appearance invariant`);
    }
    return [key, token.$value];
  }));
const output = `// Generated by scripts/generate-aspect-ratios.mjs from tokens.tokens.json.\n/** Stable standard proportions; numeric values, not runtime theme lookups. */\nexport const aspectRatios = Object.freeze(${JSON.stringify(values, null, 2)} as const);\nexport type AspectRatioToken = keyof typeof aspectRatios;\n`;
const destination = new URL("../src/components/aspect-ratio/aspect-ratios.generated.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (await readFile(destination, "utf8") !== output) throw new Error("Stale aspect ratio constants; run node scripts/generate-aspect-ratios.mjs");
} else await writeFile(destination, output);
